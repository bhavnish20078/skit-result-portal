<?php
/*
    generate_hash.php
    -----------------
    PURPOSE: A small helper tool that creates password hashes
    using YOUR OWN PHP installation, and immediately checks that
    password_verify() accepts them.

    WHY THIS FILE EXISTS:
    A password hash must be generated by the same kind of system
    that will later verify it. If a hash is copied from somewhere
    else and uses a slightly different format, password_verify()
    will silently return false and every login will fail.
    Generating the hash here removes all doubt.

    HOW TO USE:
    1. Open http://localhost/skit-result-viewer/generate_hash.php
    2. Copy the three UPDATE statements it prints.
    3. Paste them into phpMyAdmin -> skit_result_viewer -> SQL tab -> Go.
    4. Log in normally.

    IMPORTANT: Delete this file once your logins work. It is only a
    setup tool and should never exist on a real website, because it
    reveals which passwords belong to which accounts.
*/

// The sample accounts and their PLAIN TEXT passwords.
// These plain passwords are only used here to create the hashes.
$accounts = [
    "21EASKIT001" => "skit@123",
    "21EASKIT002" => "skit@456",
    "21EASKIT003" => "skit@789"
];

// The admin account lives in a separate table, so it needs its own
// UPDATE statement targeting "admins" (matched by username, not
// enrollment_no). Change the password here if you want a new one.
$adminAccounts = [
    "admin" => "admin@123"
];
