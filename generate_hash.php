// Loop through each account, hash its password, and print an UPDATE query.
foreach ($accounts as $enrollment_no => $plain_password) {

    // password_hash() creates a secure bcrypt hash.
    // PASSWORD_DEFAULT lets PHP pick the current best algorithm.
    $hash = password_hash($plain_password, PASSWORD_DEFAULT);

    // Print a ready-to-run SQL statement.
    echo "UPDATE students SET password = '" . $hash . "' WHERE enrollment_no = '" . $enrollment_no . "';\n";
}

// Same idea, but for the admins table.
foreach ($adminAccounts as $username => $plain_password) {
    $hash = password_hash($plain_password, PASSWORD_DEFAULT);
    echo "UPDATE admins SET password = '" . $hash . "' WHERE username = '" . $username . "';\n";
}
